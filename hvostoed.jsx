/* ---------- приложение ---------- */
export default function App() {
  const [screen, setScreen] = useState("menu");
  const [packIdx, setPackIdx] = useState(0);
  const [idx, setIdx] = useState(0);
  const [stars, setStars] = useState({});
  const [records, setRecords] = useState(() => {
    try { return JSON.parse(localStorage.getItem("hv-records") || "{}"); } catch (e) { return {}; }
  });
  const [crafted, setCrafted] = useState(() => {
    try { return JSON.parse(localStorage.getItem("hv-crafted") || "[]"); } catch (e) { return []; }
  });
  const [busy, setBusy] = useState(null);
  const [note, setNote] = useState(null);
  const [craftOpen, setCraftOpen] = useState(null);   // имя пресета-заготовки или null
  const [craftFail, setCraftFail] = useState(null);
  const [craftCfgs, setCraftCfgs] = useState(() => {
    try { return JSON.parse(localStorage.getItem("hv-craftcfg") || "{}"); } catch (e) { return {}; }
  });
  const abortRef = useRef(false);
  const [inbox, setInbox] = useState(() => {
    try { return JSON.parse(localStorage.getItem("hv-inbox") || "[]"); } catch (e) { return []; }
  });
  // Правила на главной больше не висят: тому, кто их прочёл, они не нужны ни разу.
  // Но первому встречному нужны, поэтому один раз показываем сами.
  const [rules, setRules] = useState(() => {
    try { return !localStorage.getItem("hv-seen"); } catch (e) { return true; }
  });
  const closeRules = () => {
    setRules(false);
    try { localStorage.setItem("hv-seen", "1"); } catch (e) {}
  };

  const cfgOf = (name) => ({ ...PRESETS[name], ...(craftCfgs[name] || {}) });
  const setCfg = (name, upd) => {
    setCraftCfgs((prev) => {
      const cur = { ...PRESETS[name], ...(prev[name] || {}) };
      const got = typeof upd === "function" ? upd(cur) : upd;
      const keep = {};
      for (const k of ["w", "h", "len", "moves", "decoys", "bridges", "turns", "spiky", "sleepy", "apples", "portals", "mechs", "voids", "peak", "breather"]) keep[k] = got[k];
      const next = { ...prev, [name]: keep };
      try { localStorage.setItem("hv-craftcfg", JSON.stringify(next)); } catch (e) {}
      return next;
    });
  };
  const resetCfg = (name) => {
    setCraftCfgs((prev) => {
      const next = { ...prev }; delete next[name];
      try { localStorage.setItem("hv-craftcfg", JSON.stringify(next)); } catch (e) {}
      return next;
    });
  };

  const saveCrafted = (next) => {
    setCrafted(next);
    try { localStorage.setItem("hv-crafted", JSON.stringify(next)); } catch (e) {}
  };

  // Крутим попытки по одной, отдавая управление интерфейсу между ними, — иначе
  // экран замирает на секунды и кажется, что игра повисла.
  async function craft(name, cfg) {
    if (busy) return;
    setNote(null); setCraftFail(null);
    abortRef.current = false;
    let made = null, tries = 0;
    const why = {};
    const bump = (t) => { why[t] = (why[t] || 0) + 1; };
    const ordinal = crafted.filter((c) => c.preset === name).length + 1;
    // пачками по 6: пауза между ними у браузера всё равно не короче ~4 мс,
    // а перерисовка счётчика на каждую попытку сама по себе дороже попытки
    const t0 = Date.now();
    outer:
    for (let round = 0; round < 200; round++) {
      setBusy({ preset: name, tries, sec: Math.round((Date.now() - t0) / 1000) });
      await new Promise((r) => setTimeout(r, 0));
      if (abortRef.current || Date.now() - t0 > 30000) break;
      for (let b = 0; b < 6; b++) {
        tries++;
        const seed = ((Date.now() + tries * 7919) >>> 0) || 1;
        let r;
        try { r = craftOnce(cfg || name, seed); } catch (e) { bump("генератор споткнулся"); continue; }
        if (!r.level) { bump(whyNom(r.fail)); continue; }
        const c = acceptCrafted(name, r, ordinal, cfg || PRESETS[name]);
        if (!c) { bump("игра не подтвердила решение"); continue; }
        made = c; break outer;
      }
    }
    setBusy(null);
    if (made) {
      saveCrafted([...crafted, made]);
      setNote(`Готово: ${made.name}.`);
      setCraftOpen(null);
    } else if (abortRef.current) {
      setNote(`Отменено на ${tries}-й попытке.`);
    } else {
      setCraftFail({ tries, sec: Math.round((Date.now() - t0) / 1000),
        rows: Object.entries(why).sort((a, b) => b[1] - a[1]).slice(0, 4) });
    }
  }
  /* Копилка партий. Уровень сам по себе почти ничего не рассказывает — присылать
     надо ПАРТИЮ: доску плюс ходы игрока плюс за что он её прислал. Тогда она
     воспроизводится клетка в клетку, и вопрос «почему не проходится» становится
     разбираемым, а не спорным. */
  function toClipboard(text, okMsg) {
    if (navigator.clipboard) navigator.clipboard.writeText(text).then(
      () => setNote(okMsg),
      () => setNote("Скопировать не вышло: браузер не дал доступ к буферу."));
    else setNote("Этот браузер не даёт доступ к буферу обмена.");
  }

  function onShare(lv, info) {
    const pi = Object.keys(PRESETS).indexOf(lv.preset);
    let code;
    try {
      code = encodeShare({ level: lv, played: info.played, lastTry: info.lastTry,
        reason: info.reason, seed: lv.seed || 0, presetIdx: pi < 0 ? null : pi, cfg: lv.cfg });
    } catch (e) { setNote("Уровень не закодировался: " + e.message); return; }
    const next = [...inbox, { code, reason: info.reason, name: lv.name || "уровень" }];
    setInbox(next);
    try { localStorage.setItem("hv-inbox", JSON.stringify(next)); } catch (e) {}
    toClipboard(code, `В копилке ${уровней(next.length)} · «${REASONS[info.reason]}» скопировано.`);
  }

  function dumpInbox() {
    if (!inbox.length) return;
    toClipboard(inbox.map((r) => `${REASONS[r.reason]} · ${r.name}\n${r.code}`).join("\n\n"),
      `Скопировано ${уровней(inbox.length)} — вставляй в чат целиком.`);
  }

  function clearInbox() {
    setInbox([]);
    try { localStorage.removeItem("hv-inbox"); } catch (e) {}
    setNote("Копилка очищена.");
  }

  function onDrop(action, id) {
    const c = crafted[id];
    if (!c) return;
    if (action === "copy") {
      const text = craftedToText(c);
      if (navigator.clipboard) navigator.clipboard.writeText(text).then(
        () => setNote(`«${c.name}» скопирован — можно прислать.`),
        () => setNote("Скопировать не вышло: браузер не дал доступ к буферу."));
      else setNote("Этот браузер не даёт доступ к буферу обмена.");
      return;
    }
    saveCrafted(crafted.filter((_, i) => i !== id));
    setNote(`«${c.name}» выброшен.`);
  }

  const craftLevels = useMemo(() => crafted.map(craftedToLevel), [crafted]);
  const packs = useMemo(() => PACKS.concat([{
    id: "craft", craft: true, name: "Мастерская",
    note: crafted.length ? "свои " + уровней(crafted.length) : "генератор уровней",
    levels: craftLevels,
  }]), [craftLevels, crafted.length]);
  const pack = packs[packIdx];
  const levels = pack.levels;
  const recKey = pack.id + ":" + idx;
  const saveRecord = (len) => setRecords((p) => {
    if ((p[recKey] || 0) >= len) return p;
    const next = { ...p, [recKey]: len };
    try { localStorage.setItem("hv-records", JSON.stringify(next)); } catch (e) {}
    return next;
  });

  return (
    <div className="hv-root">
      <style>{CSS_TEXT}</style>
      {craftOpen ? (
        <CraftModal
          base={craftOpen}
          cfg={cfgOf(craftOpen)}
          busy={busy}
          fail={craftFail}
          onSet={(upd) => { setCraftFail(null); setCfg(craftOpen, upd); }}
          onReset={() => { setCraftFail(null); resetCfg(craftOpen); }}
          onClose={() => { if (!busy) { setCraftOpen(null); setCraftFail(null); } }}
          onGo={{ run: () => craft(craftOpen, cfgOf(craftOpen)), cancel: () => { abortRef.current = true; } }}
        />
      ) : null}
      {rules ? <Rules pack={pack} onClose={closeRules} /> : null}
      {screen === "menu" ? (
        <Menu
          packs={packs}
          stars={stars}
          records={records}
          packIdx={packIdx}
          crafted={crafted}
          busy={busy}
          note={note}
          onCraft={(name) => { setCraftFail(null); setCraftOpen(name); }}
          onDrop={onDrop}
          onPack={(i) => { setPackIdx(i); setIdx(0); setNote(null); }}
          onPlay={(i) => { setIdx(i); setScreen("game"); }}
          onRules={() => setRules(true)}
          inbox={inbox.length}
          onDump={dumpInbox}
          onClearInbox={clearInbox}
        />
      ) : (
        <Game
          key={pack.id + ":" + idx}
          level={levels[Math.min(idx, levels.length - 1)]}
          record={records[recKey] || 0}
          onRecord={saveRecord}
          onExit={() => setScreen("menu")}
          onWin={(st) => setStars((p) => {
            const k = pack.id + ":" + idx;
            return { ...p, [k]: Math.max(p[k] || 0, st) };
          })}
          onNext={() => setIdx((i) => Math.min(i + 1, levels.length - 1))}
          hasNext={idx < levels.length - 1}
          onShare={(info) => onShare(levels[Math.min(idx, levels.length - 1)], info)}
        />
      )}
    </div>
  );
}

