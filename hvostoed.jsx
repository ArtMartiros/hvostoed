// Цвета раздаём по кругу, но соседям (клетки бок о бок) один цвет не даём:
// на больших полях две однотонные змеи впритык читаются как одна.
const paintPack = (lv) => {
  const owner = new Map();
  lv.snakes.forEach((s, si) => s.cells.forEach(([x, y]) => owner.set(x + "," + y, si)));
  const near = lv.snakes.map(() => new Set());
  lv.snakes.forEach((s, si) =>
    s.cells.forEach(([x, y]) =>
      [[1, 0], [-1, 0], [0, 1], [0, -1]].forEach(([dx, dy]) => {
        const o = owner.get(x + dx + "," + (y + dy));
        if (o != null && o !== si) { near[si].add(o); near[o].add(si); }
      })));
  const colors = [];
  let ci = 0;
  lv.snakes.forEach((s, si) => {
    if (s.apple) { colors[si] = "apple"; return; }
    if (s.spiky) { colors[si] = "spiky"; return; }
    if (s.sleep) { colors[si] = "sleepy"; return; }
    const taken = new Set([...near[si]].map((o) => colors[o]).filter(Boolean));
    for (let k = 0; k < ORDER.length; k++) {
      const c = ORDER[(ci + k) % ORDER.length];
      if (!taken.has(c)) { colors[si] = c; ci += k + 1; return; }
    }
    colors[si] = ORDER[ci++ % ORDER.length];
  });
  return colors;
};

const buildPack = (raw) =>
  raw.map((lv, i) => {
    const colors = paintPack(lv);
    const marks = marksOf(lv.ceiling, Math.max(...lv.snakes.map((sn) => sn.cells.length)));
    return {
      ...lv,
      id: i,
      mode: "goal",
      marks,
      target: marks[0],
      rocks: lv.rocks || [],
      bridges: lv.bridges || [],
      turns: lv.turns || [],
      portals: lv.portals || [],
      snakes: lv.snakes.map((s, si) => ({
        id: "s" + si,
        color: colors[si],
        spiky: !!s.spiky,
        sleep: !!s.sleep || !!s.apple,
        apple: !!s.apple,
        cells: s.cells,
      })),
    };
  });

/* ---------- мастерская ----------
   Уровень, собранный генератором, принимается только если его проходит код самой
   игры: тем же планировщиком, что стоит за лампочкой. Для целевого уровня план
   обязан существовать и не быть короче задуманного (иначе где-то срез), для поля
   рекорда потолком объявляется то, что игра реально сумела собрать. */
// «за 4 хода», а не «за 4 ходов»
const plural = (n, one, few, many) => {
  const d = n % 10, dd = n % 100;
  if (d === 1 && dd !== 11) return one;
  if (d >= 2 && d <= 4 && (dd < 12 || dd > 14)) return few;
  return many;
};
const ходов = (n) => n + " " + plural(n, "ход", "хода", "ходов");
const клеток = (n) => n + " " + plural(n, "клетка", "клетки", "клеток");
const уровней = (n) => n + " " + plural(n, "уровень", "уровня", "уровней");

const withIds = (snakes) => snakes.map((s, i) =>
  ({ id: "s" + i, spiky: !!s.spiky, sleep: !!s.sleep, cells: s.cells.map((c) => c.slice()) }));
/* Доска = валуны, мосты и повороты. Собирается из уровня в одном месте, чтобы игра,
   планировщик, солвер и мастерская читали одно и то же.

   Поворот — плитка пола, соединяющая две стороны клетки из четырёх. Луч, вошедший
   с открытой стороны, выходит в другую открытую; вошедший с закрытой — авария, как
   о валун: у плитки есть спина. Занятость проверяется РАНЬШЕ поворота, поэтому змея,
   лёгшая на плитку, её перекрывает — и заодно скрывает, что честно: перекрытый
   поворот не работает. */
const boardOf = (lv) => ({
  rocks: new Set((lv.rocks || []).map(([x, y]) => ckey(x, y))),
  bridges: new Set((lv.bridges || []).map(([x, y]) => ckey(x, y))),
  turns: new Map((lv.turns || []).map(([x, y, a, b]) => [ckey(x, y), a + b])),
  gates: new Map((lv.portals || []).map(([x, y, u, v]) => [ckey(x, y), [u, v]])),
});

function acceptCrafted(name, r, ordinal, cfg) {
  const lv = r.level, m = r.metrics;
  const snakes = lv.snakes.map((s) =>
    ({ cells: s.cells.map((c) => c.slice()), ...(s.spiky ? { spiky: true } : {}),
       ...(s.sleep ? { sleep: true } : {}), ...(s.apple ? { apple: true } : {}) }));
  const base = { w: lv.w, h: lv.h, snakes, bridges: lv.bridges || [], turns: lv.turns || [],
                 portals: lv.portals || [],
                 preset: name, seed: r.seed, cfg: knobsOf(cfg),
                 name: name.charAt(0).toUpperCase() + name.slice(1) + " " + ordinal };
  if (r.record) {
    const bd = boardOf(lv);
    const plan = planLongest({ w: lv.w, h: lv.h }, withIds(snakes), bd);
    if (!plan) return null;
    const got = replayPlan({ w: lv.w, h: lv.h }, withIds(snakes), plan, bd);
    if (got.broken || got.len < 2) return null;
    return { ...base, mode: "record", ceiling: got.len, proof: "beam", mass: m.mass,
      plan: plan.map((st) => st.sid),
      marks: marksOf(got.len, Math.max(...snakes.map((sn) => sn.cells.length))),
      lesson: `${m.snakes} змей · ${клеток(m.mass)} · игра собирает ${got.len} за ${ходов(got.steps)}` };
  }
  const target = lv.len;
  /* Уровень строится ИЗ плана — значит план у нас уже есть, и правильная приёмка
     не «пусть игра поищет решение заново», а «пусть игра пройдёт задуманное».
     Это и точнее (перебор упирается в бюджет и на больших досках сдаётся), и
     на порядок дешевле, и заодно ловит расхождение механики игры с генератором.
     Путь короче задуманного отсекается раньше, в craftOnce (метрика shortcut). */
  const sids = lv.moves.map((mv) => "s" + lv.snakes.findIndex((s) => s.id === mv.eater));
  if (sids.some((s) => s === "s-1")) return null;
  const got = walkSids({ w: lv.w, h: lv.h }, withIds(snakes), sids, boardOf(lv));
  if (got.bad || got.len < target) return null;
  const plan = got.steps;
  const мех = [];
  if (snakes.some((s) => s.apple)) мех.push("яблоко даёт +1");
  if (snakes.some((s) => s.spiky)) мех.push("колючую не съесть");
  if (snakes.some((s) => s.sleep && !s.apple)) мех.push("спящая не ходит");
  if ((base.bridges || []).length) мех.push("над мостом луч проходит");
  if ((base.turns || []).length) мех.push("поворот загибает луч");
  if ((base.portals || []).length) мех.push("портал уносит луч");
  // Верхняя отметка — длина задуманного плана: она достижима ПО ПОСТРОЕНИЮ, и это
  // только что подтвердил walkSids кодом самой игры. Отметки ниже считает marksOf.
  const marks = marksOf(target, Math.max(...snakes.map((sn) => sn.cells.length)));
  return { ...base, mode: "goal", ceiling: target, marks, target: marks[0], plan: sids,
    lesson: `Отметки ${marks.join(" · ")} за ${ходов(plan.length)} · решений ${m.sols} · безопасных тапов ${Math.round(100 * m.safety)}%`
      + (мех.length ? " · " + мех.join(", ") : "") };
}

