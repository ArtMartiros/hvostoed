function RayView({ ray, from, color }) {
  const [hx, hy] = toPx(from);
  // луч может гнуться в поворотах, поэтому рисуем ломаную по его собственным клеткам
  const pts = [[hx, hy], ...ray.gap.map(([x, y]) => [x * CS + CS / 2, y * CS + CS / 2])];
  const tail = pts[pts.length - 1];
  /* Стенка СВОЕЙ же плитки — единственная преграда, до которой луч не пролетает
     ни одной клетки: голова уже лежит в жёлобе. Поэтому крестик ставим на саму
     стенку (46 — там её рисует TurnWalls), а не в центр клетки: в центре голова,
     и крестик поверх неё читается как «сломалась змея», а не «здесь глухо». */
  const own = ray.hitCell && ray.hitCell[0] === from[0] && ray.hitCell[1] === from[1];
  const mark = ray.hitCell
    ? (own ? [hx + ray.dir[0] * 46, hy + ray.dir[1] * 46]
           : [ray.hitCell[0] * CS + CS / 2, ray.hitCell[1] * CS + CS / 2])
    : null;
  const back = own ? 0 : 34;                    // упор луча не доходит до центра преграды
  const x2 = mark ? mark[0] - ray.dir[0] * back : tail[0] + ray.dir[0] * CS * 0.62;
  const y2 = mark ? mark[1] - ray.dir[1] * back : tail[1] + ray.dir[1] * CS * 0.62;
  pts.push([x2, y2]);
  const dPath = dStr(pts);
  return (
    <g style={{ pointerEvents: "none" }}>
      <path d={dPath} fill="none" stroke={color} strokeWidth="10"
        strokeLinecap="round" strokeLinejoin="round" strokeDasharray="4 26" className="hv-dash" />
      {ray.kind === "edge" ? (
        <path d={"M" + x2 + " " + y2 + " m" + (-ray.dir[0] * 16) + " " + (-ray.dir[1] * 16) +
                 " l" + (ray.dir[0] * 26 - ray.dir[1] * 14) + " " + (ray.dir[1] * 26 - ray.dir[0] * 14) +
                 " M" + x2 + " " + y2 + " m" + (-ray.dir[0] * 16) + " " + (-ray.dir[1] * 16) +
                 " l" + (ray.dir[0] * 26 + ray.dir[1] * 14) + " " + (ray.dir[1] * 26 + ray.dir[0] * 14)}
          stroke={color} strokeWidth="10" strokeLinecap="round" fill="none" />
      ) : (
        <g transform={"translate(" + mark[0] + " " + mark[1] + ")"}>
          <line x1="-15" y1="-15" x2="15" y2="15" stroke={color} strokeWidth="11" strokeLinecap="round" />
          <line x1="15" y1="-15" x2="-15" y2="15" stroke={color} strokeWidth="11" strokeLinecap="round" />
        </g>
      )}
    </g>
  );
}

/* ---------- игра ---------- */
function Game({ level, onExit, onWin, onNext, hasNext, record, onRecord, onShare }) {
  const isRec = level.mode === "record";
  const isSec = level.mode === "sections";
  const [open, setOpen] = useState(1);        // сколько комнат открыто
  const [errors, setErrors] = useState(0);    // счётчик ошибок: жизни бесконечны
  const checkpointRef = useRef(null);         // состояние на миг открытия комнаты
  const [snakes, setSnakes] = useState(() => clone(level.snakes));
  const [runBest, setRunBest] = useState(() => maxLen(level.snakes));
  const [hints, setHints] = useState(0);
  const hintsRef = useRef(0);          // commit читает счётчик синхронно, состояние туда не успевает
  const planRef = useRef(new Map());   // состояние поля -> змея, по которой надо тапнуть
  const [history, setHistory] = useState([]);
  // журнал партии: без него присланный уровень почти ничего не говорит — важно
  // не «уровень плохой», а на каком ходу человек свернул и что нажимал
  const [log, setLog] = useState([]);
  const lastTryRef = useRef(null);
  const [shareOpen, setShareOpen] = useState(false);
  const send = (reason) => {
    setShareOpen(false);
    onShare({ reason, played: log, lastTry: lastTryRef.current });
  };
  const [phase, setPhase] = useState("idle"); // idle | anim | crash | won | lost | done
  const [fx, setFx] = useState(null);
  const [toast, setToast] = useState(null);
  const [plus, setPlus] = useState(null);
  const [wonInfo, setWonInfo] = useState(null);
  const [lostReason, setLostReason] = useState(null);
  const [crashed, setCrashed] = useState(false); // авария: поле не менялось, «Продолжить» бесплатен
  const regRef = useRef({});
  const rafRef = useRef(null);
  const fxTimerRef = useRef(null);
  const crashTimerRef = useRef(null);
  /* Закрытые комнаты для луча — сплошной валун: авария, а не вылет. Терять
     массу о стену, которая скоро исчезнет, было бы несправедливо. */
  const board = useMemo(() => {
    const b = boardOf(level);
    if (isSec) for (let k = open; k < level.sections.length; k++) {
      const r = level.sections[k];
      for (let y = r.y; y < r.y + r.h; y++) for (let x = r.x; x < r.x + r.w; x++) b.rocks.add(ckey(x, y));
    }
    return b;
  }, [level, open]);
  const reduced = useMemo(
    () => typeof window !== "undefined" && window.matchMedia &&
          window.matchMedia("(prefers-reduced-motion: reduce)").matches, []
  );

  useEffect(() => () => { cancelAnimationFrame(rafRef.current); clearTimeout(fxTimerRef.current); clearTimeout(crashTimerRef.current); }, []);

  const best = maxLen(snakes);
  // Отметка, которую игрок сейчас берёт, и запас до неё. Запас = сколько длины ещё
  // можно потерять на выпусках, не потеряв эту звезду: обед массу сохраняет, теряет
  // её только вылет. Без этого числа на бюджетных уровнях не сыграть.
  const onBoard = snakes.reduce((a, s) => a + s.cells.length, 0);
  const aim = isRec || isSec ? null : (level.marks.find((m) => m > best) || level.ceiling);
  const hasBudget = !isRec && !isSec && level.snakes.reduce((a, s) => a + s.cells.length, 0) > level.marks[0];
  const slack = onBoard - aim;
  const idle = phase === "idle";
  const canEatAny = idle && snakes.some((s) => !s.sleep && raycast(snakes, s.id, level.w, level.h, board).kind === "tail");
  const canLaunchAny = !isSec && idle && snakes.some((s) => !s.sleep && raycast(snakes, s.id, level.w, level.h, board).kind === "edge");
  const secStuck = isSec && idle && !canEatAny && snakes.length > 1;

  function showFx(next, ms) {
    clearTimeout(fxTimerRef.current);
    setFx(next);
    if (ms) fxTimerRef.current = setTimeout(() => { setFx(null); setToast(null); }, ms);
  }

  function part(root, name) { return root ? root.querySelector('[data-part="' + name + '"]') : null; }

  function commit(mv) {
    setSnakes(mv.finalSnakes);
    if (mv.gained > 0) {
      const e = mv.finalSnakes.find((s) => s.id === mv.moverId);
      if (e) {
        setPlus({ x: e.cells[0][0], y: e.cells[0][1], n: mv.gained, sign: "+", key: Date.now() });
        if (navigator.vibrate) navigator.vibrate(18);
      }
    } else if (mv.lost > 0) {
      setPlus({ x: mv.lostAt[0], y: mv.lostAt[1], n: mv.lost, sign: "−", key: Date.now() });
    }
    const ml = maxLen(mv.finalSnakes);
    if (ml > runBest) { setRunBest(ml); if (isRec && hintsRef.current === 0) onRecord(ml); }
    /* Комнаты: одна змея в открытой области — комната собрана. Либо открываем
       следующую (её змеи доезжают на доску, открытие — чекпоинт: история
       чистится, отмотки назад через границу нет), либо доска собрана целиком. */
    if (isSec) {
      if (mv.finalSnakes.length === 1) {
        if (open < level.sections.length) {
          const merged = mv.finalSnakes.concat(clone(level.sections[open].snakes));
          checkpointRef.current = clone(merged);
          setSnakes(merged);
          setOpen(open + 1);
          setHistory([]);
          setToast(open + 1 === level.sections.length ? "Последняя комната открыта!" : "Комната открыта!");
        } else {
          setWonInfo({ len: ml, stars: 3, errors });
          setPhase("won");
          onWin(3);
          return;
        }
      }
      setPhase("idle");
      return;
    }
    /* Смерть по массе. Обед массу сохраняет, теряется она только на вылете, а нижняя
       отметка по построению не больше стартовой массы. Значит «клеток на поле меньше
       нижней отметки» — ТОЧНЫЙ признак проигрыша за одно сложение, без перебора; он
       ловит главную необратимую ошибку — лишний выпуск. Молчать тут нельзя: правило
       порога (партия идёт, пока можно расти) само по себе позволяет расти вечно, ни
       разу не добравшись до отметки, — и игрок ходит по мёртвому уровню, не зная. */
    if (!isRec && mv.finalSnakes.reduce((a, s) => a + s.cells.length, 0) < level.marks[0]) {
      clearTimeout(crashTimerRef.current);
      setLostReason("Улетело слишком много: на поле осталось меньше клеток, чем нужно даже на первую отметку.");
      setPhase("lost");
      return;
    }
    // Нижняя отметка — порог, а не финиш: пока змея может расти, партия идёт,
    // и каждый лишний обед — это шаг к следующей звезде.
    const anyEat = mv.finalSnakes.some((s) => !s.sleep && raycast(mv.finalSnakes, s.id, level.w, level.h, board).kind === "tail");
    if (!anyEat && !canGrow(level, mv.finalSnakes, board, ml)) {
      finish(mv.finalSnakes, ml);
      return;
    }
    setPhase("idle");
  }

  /* Конец партии — либо рост доказуемо невозможен, либо игрок забрал результат сам.
     Уровень не закрывается в тот миг, когда длина пересекает нижнюю отметку: доска
     дальше и есть игра, следующая отметка берётся ровно тем, что ты доедаешь поле.
     Звёзды считаются по ДЛИНЕ в конце партии — по тому, докуда доросла змея. */
  function finish(fin, ml) {
    clearTimeout(crashTimerRef.current);
    if (isRec) { setPhase("done"); return; }
    const stars = level.marks.filter((m) => ml >= m).length;
    if (stars > 0) {
      setWonInfo({ len: ml, stars, next: level.marks.find((m) => ml < m) || null });
      setPhase("won");
      onWin(stars);
    } else {
      setLostReason("Съесть больше некого — змея не дотянула даже до первой отметки.");
      setPhase("lost");
    }
  }

  // Авария: тап по змее, чей луч заблокирован. Поле не меняется,
  // но уровень завален — после тряски показываем экран поражения.
  function crash(reason, sid, ray, from) {
    setToast(reason);
    showFx({ ray, from, color: "#E05548", shakeId: sid });
    setPhase("crash");
    if (isRec) {                       // на рекордном поле промах — просто тычок, партия идёт дальше
      crashTimerRef.current = setTimeout(() => setPhase("idle"), 420);
      return;
    }
    if (isSec) {                       // в комнатах ошибка бесплатна: доска не тронута, крутится счётчик
      setErrors((e) => e + 1);
      crashTimerRef.current = setTimeout(() => { setPhase("idle"); setFx(null); }, 650);
      return;
    }
    setCrashed(true);
    setLostReason(reason);
    crashTimerRef.current = setTimeout(() => setPhase("lost"), 700);
  }

  function forgiveCrash() {
    clearTimeout(crashTimerRef.current);
    setCrashed(false); setLostReason(null);
    setPhase("idle"); setFx(null); setToast(null);
  }

  function runMove(mv) {
    setPhase("anim");
    if (reduced) { commit(mv); return; }
    const root = regRef.current[mv.moverId];
    const preyRoot = mv.preyId ? regRef.current[mv.preyId] : null;
    if (!root) { commit(mv); return; }
    const P = mv.trackCells.map(toPx);
    const preyP = mv.preyCells ? mv.preyCells.map(toPx) : null;
    const pathLen = mv.pathCells.length;
    const gapLen = pathLen - (mv.preyCells ? mv.preyCells.length : 0);
    const nfPre = [0]; const ffPre = [0];
    for (let i = 0; i < pathLen; i++) {
      nfPre.push(nfPre[i] + (mv.foodFlags[i] ? 0 : 1));
      ffPre.push(ffPre[i] + (mv.foodFlags[i] ? 1 : 0));
    }
    const body = part(root, "body"), outline = part(root, "outline"), touch = part(root, "touch");
    const stripes = part(root, "stripes"), spikesG = part(root, "spikes");
    const headG = part(root, "headG"), rotG = part(root, "rotG");
    const headCircle = part(root, "headCircle"), num = part(root, "num");
    const pBody = part(preyRoot, "body"), pOutline = part(preyRoot, "outline"), pTouch = part(preyRoot, "touch");
    const pStripes = part(preyRoot, "stripes"), pHeadG = part(preyRoot, "headG");
    if (stripes) stripes.setAttribute("opacity", "0");
    if (spikesG) spikesG.setAttribute("opacity", "0.25");
    if (pStripes) pStripes.setAttribute("opacity", "0");
    const cellDur = mv.kind === "launch" ? 66 : Math.max(46, Math.min(90, 1250 / pathLen));
    const dur = pathLen * cellDur;
    const t0 = performance.now();

    const frame = (now) => {
      // rAF передаёт время начала кадра — оно бывает РАНЬШЕ t0, снятого при
      // старте анимации; отрицательный p давал индекс −1 и NaN ронял кадр
      const p = Math.min(1, Math.max(0, (now - t0) / dur));
      const u = mv.kind === "launch"
        ? pathLen * (0.3 * p + 0.7 * p * p)
        : pathLen * p;
      const k = Math.min(pathLen - 1, Math.floor(u));
      const fu = u - Math.floor(u);
      const h = (mv.n0 - 1 + u) * CS;
      let tAdv = nfPre[Math.floor(Math.min(u, pathLen))];
      if (u < pathLen && !mv.foodFlags[k]) tAdv += fu;
      const t = tAdv * CS;
      const dd = dStr(samplePts(P, t, h));
      if (body) body.setAttribute("d", dd);
      if (outline) outline.setAttribute("d", dd);
      if (touch) touch.setAttribute("d", dd);
      const hp = ptAt(P, h);
      if (headG) headG.setAttribute("transform", "translate(" + hp[0].toFixed(1) + " " + hp[1].toFixed(1) + ")");
      if (rotG) rotG.setAttribute("transform", "rotate(" + angleAt(P, h).toFixed(1) + ")");
      if (num) {
        const nv = String(mv.n0 + ffPre[Math.floor(Math.min(u, pathLen))]);
        if (num.textContent !== nv && navigator.vibrate) navigator.vibrate(8);
        num.textContent = nv;
      }
      if (headCircle) {
        const r = mv.kind === "eat" && u > gapLen && u < pathLen
          ? 43 + 9 * Math.abs(Math.sin(Math.PI * fu)) : 43;
        headCircle.setAttribute("r", r.toFixed(1));
      }
      if (preyP && preyRoot) {
        const into = Math.max(0, u - gapLen) * CS;
        const rem = (mv.preyCells.length - 1) * CS - into;
        if (rem > 26) {
          const pd = dStr(samplePts(preyP, 0, rem));
          if (pBody) pBody.setAttribute("d", pd);
          if (pOutline) pOutline.setAttribute("d", pd);
          if (pTouch) pTouch.setAttribute("d", pd);
        } else {
          if (pBody) pBody.setAttribute("opacity", "0");
          if (pOutline) pOutline.setAttribute("opacity", "0");
          const op = Math.max(0, (rem + 10) / 36);
          if (pHeadG) pHeadG.setAttribute("opacity", op.toFixed(2));
        }
      }
      if (p < 1) {
        rafRef.current = requestAnimationFrame(frame);
      } else {
        if (stripes) stripes.setAttribute("opacity", "1");
        if (spikesG) spikesG.setAttribute("opacity", "1");
        if (headCircle) headCircle.setAttribute("r", "43");
        commit(mv);
      }
    };
    rafRef.current = requestAnimationFrame(frame);
  }

  function tapSnake(sid) {
    if (phase !== "idle") return;
    setToast(null); setFx(null);
    const s = snakes.find((q) => q.id === sid);
    lastTryRef.current = sid;
    if (s.apple) { setToast("Яблоко не ходит — его едят. Наведи на него чью-нибудь голову."); return; }
    if (s.sleep) { setToast("Спящая змея не ходит — её можно только съесть."); return; }
    const ray = raycast(snakes, sid, level.w, level.h, board);
    const nom = COLORS[s.color].nom;
    const Nom = nom.charAt(0).toUpperCase() + nom.slice(1);
    if (ray.kind === "tail") {
      const mv = buildEatMove(snakes, sid, ray);
      setHistory((hh) => [...hh, { snakes: clone(snakes), runBest }]);
      setLog((l) => [...l, sid]);
      runMove(mv);
    } else if (ray.kind === "edge" && isSec) {
      // вылетов в комнатах нет: все змеи нужны, взгляд за край — ошибка, доска не меняется
      crash(Nom + " змея улетела бы с доски — здесь так нельзя, каждая змея нужна.", sid, ray, s.cells[0]);
    } else if (ray.kind === "edge") {
      const mv = buildLaunchMove(snakes, sid, ray);
      setHistory((hh) => [...hh, { snakes: clone(snakes), runBest }]);
      setLog((l) => [...l, sid]);
      runMove(mv);
    } else if (ray.kind === "self") {
      crash(Nom + " змея смотрит на собственный хвост — уроборос запрещён.", sid, ray, s.cells[0]);
    } else if (ray.kind === "rock") {
      // в комнатах валунов нет — любой «валун» это крышка закрытой комнаты
      crash(isSec ? Nom + " змея уткнулась в закрытую комнату." : Nom + " змея врезалась в валун.", sid, ray, s.cells[0]);
    } else if (ray.kind === "loop") {
      crash(Nom + " змея загнала луч в кольцо порталов — выхода нет.", sid, ray, s.cells[0]);
    } else if (ray.kind === "turnBack") {
      crash(Nom + " змея ткнулась в стенку поворота — с этой стороны глухо.", sid, ray, s.cells[0]);
    } else if (ray.kind === "spikyTail") {
      crash(Nom + " змея укололась о шипы — колючий хвост не съесть.", sid, ray, s.cells[0]);
    } else if (ray.kind === "head") {
      const t = snakes.find((q) => q.id === ray.target);
      crash(Nom + " змея врезалась в голову " + COLORS[t.color].gen + " — есть можно только за хвост.", sid, ray, s.cells[0]);
    } else {
      const t = snakes.find((q) => q.id === ray.target);
      crash(Nom + " змея врезалась в тело " + COLORS[t.color].gen + " змеи.", sid, ray, s.cells[0]);
    }
  }

  /* Задуманный план, разложенный по состояниям. Уровень построен ИЗ него, так что
     пока игрок с него не сошёл, подсказка точна по построению и бесплатна.
     Перебор — только для тех, кто отклонился. */
  const madeRef = useRef(null);
  function made() {
    if (madeRef.current) return madeRef.current;
    const m = new Map();
    if (level.plan && level.plan.length) {
      const got = walkSids(level, clone(level.snakes), level.plan, board);
      if (!got.bad) for (const st of got.steps) m.set(st.k, st.sid);
    }
    madeRef.current = m;
    return m;
  }

  function hint() {
    if (phase !== "idle") return;
    if (isSec) { setToast("В комнатах подсказки пока нет — прототип."); return; }
    const k = stateKey(snakes);
    let sid = made().get(k);
    if (sid == null) sid = planRef.current.get(k);
    if (sid == null) {
      const goal = !isRec && best < level.ceiling;
      const out = {};
      const plan = goal
        ? (planGoal(level, snakes, board, out) || planLongest(level, snakes, board))
        : planLongest(level, snakes, board);
      if (!plan || !plan.length) {
        setToast(!goal
          ? "Больше не вырасти — партию можно заканчивать."
          : out.exhausted
            ? "Ты ушёл от задуманного пути, и отсюда решения я не вижу. Отмени ход."
            : "Отсюда до потолка уже не дорасти. Отмени ход или начни заново.");
        return;
      }
      planRef.current = new Map(plan.map((st) => [st.k, st.sid]));
      sid = planRef.current.get(k) != null ? planRef.current.get(k) : plan[0].sid;
    }
    hintsRef.current += 1;
    setHints(hintsRef.current);
    tapSnake(sid);
  }

  function undo() {
    if (phase === "anim") return;
    if (crashed) { forgiveCrash(); return; }
    if (!history.length) return;
    const last = history[history.length - 1];
    setHistory((hh) => hh.slice(0, -1));
    setLog((l) => l.slice(0, -1));
    setSnakes(last.snakes);
    setRunBest(last.runBest != null ? last.runBest : maxLen(last.snakes));
    setPhase("idle"); setWonInfo(null); setLostReason(null);
    setFx(null); setToast(null); setPlus(null);
  }

  function roomAgain() {              // рестарт КОМНАТЫ: откат к чекпоинту открытия, счётчик ошибок живёт
    if (phase === "anim") return;
    setSnakes(clone(checkpointRef.current || level.snakes));
    setHistory([]);
    setPhase("idle"); setWonInfo(null); setLostReason(null); setCrashed(false);
    setFx(null); setToast(null); setPlus(null);
  }

  function restart() {
    if (phase === "anim") return;
    setOpen(1); setErrors(0); checkpointRef.current = null;
    clearTimeout(crashTimerRef.current);
    setSnakes(clone(level.snakes)); setHistory([]); setLog([]); setRunBest(maxLen(level.snakes));
    hintsRef.current = 0; setHints(0); planRef.current = new Map();
    setPhase("idle"); setWonInfo(null); setLostReason(null); setCrashed(false);
    setFx(null); setToast(null); setPlus(null);
  }

  const taken = isRec ? 0 : level.marks.filter((m) => best >= m).length;
  const reached = !isRec && taken > 0;
  const stuckMsg =
    idle && !canEatAny && canLaunchAny
      ? "Съесть некого. Выпусти змею, чтобы расчистить путь, или закончи партию."
      : null;

  const W = level.w * CS, H = level.h * CS;
  const cells = [];
  for (let y = 0; y < level.h; y++)
    for (let x = 0; x < level.w; x++)
      cells.push(
        <rect key={x + "-" + y} x={x * CS + 5} y={y * CS + 5} width={CS - 10} height={CS - 10}
          rx="16" fill={(x + y) % 2 ? "#F5ECDB" : "#FAF3E6"} />
      );

  return (
    <div className="hv-screen">
      <header className="hv-top">
        <button className="hv-icon" onClick={onExit} aria-label="К уровням"><ChevronLeft size={22} /></button>
        <div className="hv-lvname"><span className="hv-lvnum">{level.id + 1}</span> {level.name}</div>
        <button className={"hv-icon" + (hints ? " hv-hinted" : "")} onClick={hint}
          disabled={phase !== "idle"} aria-label="Подсказать ход">
          <Lightbulb size={19} />
          {hints ? <span className="hv-hintn">{hints}</span> : null}
        </button>
        <button className="hv-icon" onClick={undo} disabled={(!history.length && !crashed) || phase === "anim"} aria-label="Отменить ход">
          <Undo2 size={20} />
        </button>
        <button className="hv-icon" onClick={restart} disabled={phase === "anim"} aria-label="Заново">
          <RotateCcw size={19} />
        </button>
        <button className="hv-icon" onClick={() => setShareOpen(true)} aria-label="Отправить уровень">
          <Flag size={18} />
        </button>
      </header>

      {isSec ? (
        <div className="hv-goalrow">
          <span className="hv-goal">Комната {open} / {level.sections.length}</span>
          <div className="hv-bar" role="progressbar" aria-valuenow={open} aria-valuemax={level.sections.length}>
            <div className="hv-fill" style={{ width: (open / level.sections.length) * 100 + "%" }} />
          </div>
          <span className="hv-count">длина {best} · ошибок {errors}</span>
        </div>
      ) : isRec ? (
        <div className="hv-goalrow">
          <span className="hv-goal rec">Рекорд {Math.max(record || 0, runBest)}</span>
          <div className="hv-bar" role="progressbar" aria-valuenow={runBest} aria-valuemax={level.ceiling}>
            <div className="hv-fill" style={{ width: Math.min(100, (runBest / level.ceiling) * 100) + "%" }} />
            {(level.marks || []).map((m) => (
              <i key={m} className={"hv-mark" + (runBest >= m ? " hit" : "")} style={{ left: (m / level.ceiling) * 100 + "%" }} />
            ))}
          </div>
          <span className="hv-count">{runBest} / {level.ceiling}</span>
        </div>
      ) : (
        <div className="hv-goalrow">
          <span className="hv-goal">Длина</span>
          <div className="hv-bar" role="progressbar" aria-valuenow={best} aria-valuemax={level.ceiling}>
            <div className="hv-fill" style={{ width: Math.min(100, (best / level.ceiling) * 100) + "%" }} />
            {level.marks.map((m) => (
              <i key={m} className={"hv-mark" + (best >= m ? " hit" : "")} style={{ left: (m / level.ceiling) * 100 + "%" }} />
            ))}
          </div>
          <span className="hv-count">{best} / {level.ceiling}</span>
        </div>
      )}

      {hasBudget ? (
        <div className={"hv-slack" + (slack <= 0 ? " tight" : "")}>
          Запас: <b>{Math.max(0, slack)}</b>{slack > 0 ? " — столько можно отпустить, не потеряв звезду" : " — больше терять нечего"}
        </div>
      ) : null}

      <div className="hv-boardwrap" onPointerDown={() => { setFx(null); setToast(null); }}>
        <svg className="hv-board" viewBox={"0 0 " + W + " " + H} style={{ aspectRatio: W + " / " + H }}>
          <defs>
            <clipPath id="hv-clip"><rect x="0" y="0" width={W} height={H} rx="20" /></clipPath>
          </defs>
          <rect x="0" y="0" width={W} height={H} rx="20" fill="#FFFDF8" />
          {cells}
          {isSec && level.sections.slice(open).map((r, k) => (
            <g key={"lid" + (open + k)}>
              <rect x={r.x * CS + 4} y={r.y * CS + 4} width={r.w * CS - 8} height={r.h * CS - 8}
                rx="18" fill="#E8DCC5" stroke="#DBCCAE" strokeWidth="3" />
              <text x={r.x * CS + (r.w * CS) / 2} y={r.y * CS + (r.h * CS) / 2 + 16}
                textAnchor="middle" fontSize="46" fontWeight="700" fill="#C4B292">?</text>
            </g>
          ))}
          {(level.turns || []).map(([x, y, a, b]) => <TurnFloor key={"t" + x + "-" + y} x={x} y={y} a={a} b={b} />)}
          {(level.portals || []).map(([x, y, u, v], i) => (
            <g key={"g" + i}>
              <Gate x={x} y={y} into pair={i} />
              <Gate x={u} y={v} pair={i} />
            </g>
          ))}
          {(level.bridges || []).map(([x, y]) => <BridgeFloor key={"bf" + x + "-" + y} x={x} y={y} />)}
          {level.rocks.map(([x, y]) => <Rock key={"r" + x + "-" + y} x={x} y={y} />)}
          <g clipPath="url(#hv-clip)">
            {snakes.map((s) => (s.apple ? (
              <AppleView key={s.id} snake={s} regRef={regRef}
                shaking={fx && fx.shakeId === s.id} onTap={tapSnake} />
            ) : (
              <SnakeView key={s.id} snake={s} regRef={regRef}
                shaking={fx && fx.shakeId === s.id} onTap={tapSnake} />
            )))}
          </g>
          {(level.bridges || []).map(([x, y]) => <BridgeRail key={"br" + x + "-" + y} x={x} y={y} />)}
          {(level.turns || []).map(([x, y, a, b]) => <TurnWalls key={"tw" + x + "-" + y} x={x} y={y} a={a} b={b} />)}
          {fx && fx.ray && <RayView ray={fx.ray} from={fx.from} color={fx.color} />}
          {plus && (
            <text key={plus.key} className="hv-plus" x={plus.x * CS + CS / 2} y={plus.y * CS - 6}
              textAnchor="middle" fontFamily="Rubik, sans-serif" fontWeight="800" fontSize="46"
              fill={plus.sign === "−" ? "#C0532A" : "#2F6E1F"} stroke="#FFFDF4" strokeWidth="6" paintOrder="stroke">
              {plus.sign}{plus.n}
            </text>
          )}
        </svg>

        {phase === "won" && wonInfo && (
          <div className="hv-overlay">
            <div className="hv-card">
              {!isSec && (
                <div className="hv-stars">
                  {[0, 1, 2].map((i) => (
                    <Star key={i} size={34} className="hv-star" style={{ animationDelay: i * 0.12 + "s" }}
                      fill={i < wonInfo.stars ? "#EFAF3C" : "none"}
                      color={i < wonInfo.stars ? "#EFAF3C" : "#DACDB6"} />
                  ))}
                </div>
              )}
              <div className="hv-wontitle">{isSec ? "Доска собрана!" : "Уровень пройден"}</div>
              <div className="hv-wonsub">
                {isSec
                  ? "Все комнаты открыты и съедены. Длина змеи: " + wonInfo.len +
                    (wonInfo.errors ? " · ошибок по пути: " + wonInfo.errors : " · без единой ошибки!")
                  : "Длина змеи: " + wonInfo.len + " из " + level.ceiling +
                    (wonInfo.next ? " · до следующей отметки не хватило " + (wonInfo.next - wonInfo.len)
                      : " — это потолок поля, больше тут не вырасти")}
              </div>
              <div className="hv-btnrow">
                <button className="hv-btn ghost good" onClick={() => send(0)}><Star size={14} /> Нравится</button>
                <button className="hv-btn ghost" onClick={restart}>Ещё раз</button>
                {hasNext
                  ? <button className="hv-btn main" onClick={onNext}><Play size={16} /> Дальше</button>
                  : <button className="hv-btn main" onClick={onExit}>К уровням</button>}
              </div>
            </div>
          </div>
        )}

        {phase === "done" && (
          <div className="hv-overlay">
            <div className="hv-card">
              <div className="hv-stars">
                {(level.marks || []).map((m, i) => (
                  <Star key={m} size={34} className="hv-star" style={{ animationDelay: i * 0.12 + "s" }}
                    fill={runBest >= m ? "#EFAF3C" : "none"} color={runBest >= m ? "#EFAF3C" : "#DACDB6"} />
                ))}
              </div>
              <div className="hv-wontitle">{runBest > (record || 0) ? "Новый рекорд!" : "Партия окончена"}</div>
              <div className="hv-wonsub">
                Самая длинная змея: <b>{runBest}</b>
                {level.proof === "beam" ? " · машина собирает " + level.ceiling : " из " + level.ceiling}
                {runBest > (record || 0) ? "" : " · твой рекорд " + (record || 0)}
              </div>
              {hints ? <div className="hv-hintnote">Партия с подсказками ({hints}) — в рекорд не идёт</div> : null}
              <div className="hv-btnrow">
                <button className="hv-btn ghost" onClick={undo} disabled={!history.length}>
                  <Undo2 size={15} /> Отменить ход
                </button>
                <button className="hv-btn main" onClick={restart}><RotateCcw size={15} /> Ещё раз</button>
              </div>
            </div>
          </div>
        )}

        {shareOpen && (
          <div className="hv-overlay" onClick={() => setShareOpen(false)}>
            <div className="hv-card" onClick={(e) => e.stopPropagation()}>
              <div className="hv-wontitle">Отправить уровень</div>
              <div className="hv-wonsub">
                Уйдёт доска и твои ходы ({log.length}) — этого хватает, чтобы повторить партию клетка в клетку.
              </div>
              <div className="hv-reasons">
                {REASONS.map((nom, i) => (
                  <button key={nom} className={"hv-btn ghost" + (i === 0 ? " good" : "")}
                    onClick={() => send(i)}>{i === 0 ? "★ " : ""}{nom}</button>
                ))}
              </div>
            </div>
          </div>
        )}

        {phase === "lost" && (
          <div className="hv-overlay">
            <div className="hv-card">
              <div className="hv-wontitle lost">{crashed ? "Авария!" : "Не вышло"}</div>
              <div className="hv-wonsub">{lostReason}</div>
              <div className="hv-btnrow">
                <button className="hv-btn ghost" onClick={() => send(crashed ? 2 : 1)}>
                  <Flag size={14} /> Прислать
                </button>
                {crashed ? (
                  <button className="hv-btn ghost" onClick={forgiveCrash}>
                    <Undo2 size={15} /> Продолжить
                  </button>
                ) : (
                  <button className="hv-btn ghost" onClick={undo} disabled={!history.length}>
                    <Undo2 size={15} /> Отменить ход
                  </button>
                )}
                <button className="hv-btn main" onClick={restart}><RotateCcw size={15} /> Заново</button>
              </div>
            </div>
          </div>
        )}
      </div>

      <footer className="hv-foot">
        {toast ? (
          <div className="hv-toast">{toast}</div>
        ) : secStuck ? (
          <div className="hv-toast warn">
            Комната заперта — никто никого не достаёт.
            <button className="hv-endbtn" onClick={roomAgain}>Комнату заново</button>
          </div>
        ) : stuckMsg ? (
          <div className="hv-toast warn">
            {stuckMsg}
            <button className="hv-endbtn" onClick={() => finish(snakes, best)}>Закончить</button>
          </div>
        ) : reached && idle ? (
          <div className="hv-toast good">
            {taken === 3 ? "Потолок поля взят: " + best + ". Три звезды твои."
              : "Отметок взято: " + taken + " из 3. До следующей — " + (aim - best) + "."}
            <button className="hv-endbtn" onClick={() => finish(snakes, best)}>Забрать</button>
          </div>
        ) : (
          <div className="hv-lesson">{level.lesson}</div>
        )}
      </footer>
    </div>
  );
}

