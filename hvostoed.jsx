/* ---------- логика (идентична солверу) ---------- */
const SIDES = { n: [0, -1], s: [0, 1], e: [1, 0], w: [-1, 0] };
const sideName = (v) => (v[0] === 1 ? "e" : v[0] === -1 ? "w" : v[1] === 1 ? "s" : "n");
const facing = (cells) => [cells[0][0] - cells[1][0], cells[0][1] - cells[1][1]];
const ckey = (x, y) => x + "," + y;

function occMap(snakes) {
  const m = new Map();
  snakes.forEach((s) =>
    s.cells.forEach(([x, y], ci) => m.set(ckey(x, y), { sid: s.id, ci, len: s.cells.length, spiky: s.spiky }))
  );
  return m;
}

// мост: луч всегда проходит НАД клеткой (занятость не читается), пересечься
// змеи могут только тут; хвост на мосту с этого направления не съесть
function raycast(snakes, sid, W, H, board) {
  const s = snakes.find((q) => q.id === sid);
  let [dx, dy] = facing(s.cells);
  const occ = occMap(snakes);
  let [x, y] = s.cells[0];
  const gap = [];
  /* Голова может лежать на плитке поворота — луч рождается внутри жёлоба, а цикл
     клетку головы не читает. Без этой проверки стенка держала только снаружи
     (обед сквозь стену, жалоба игрока). Гнуть нечего: у такого луча нет стороны
     входа — открытая сторона выпускает, закрытая останавливает. */
  const own = board.turns.get(ckey(x, y));
  if (own) {
    const out = sideName([dx, dy]);
    if (own[0] !== out && own[1] !== out)
      return { kind: "turnBack", gap, hitCell: [x, y], dir: [dx, dy] };
  }
  const cap = 4 * W * H + 8;                    // порталы можно замкнуть в кольцо
  for (let step = 0; ; step++) {
    if (step > cap) return { kind: "loop", gap, dir: [dx, dy] };
    x += dx; y += dy;
    if (x < 0 || y < 0 || x >= W || y >= H) return { kind: "edge", gap, dir: [dx, dy] };
    if (board.rocks.has(ckey(x, y))) return { kind: "rock", gap, hitCell: [x, y], dir: [dx, dy] };
    if (board.bridges.has(ckey(x, y))) { gap.push([x, y]); continue; }
    // спина поворота — стена даже под лежащей змеёй: закрытая сторона читается
    // РАНЬШЕ занятости, иначе обед проходил сквозь стену (жалоба игрока)
    const t = board.turns.get(ckey(x, y));
    const from = t ? sideName([-dx, -dy]) : null;
    if (t && t[0] !== from && t[1] !== from) return { kind: "turnBack", gap, hitCell: [x, y], dir: [dx, dy] };
    const hit = occ.get(ckey(x, y));
    if (hit) {
      if (hit.sid === sid) return { kind: "self", gap, hitCell: [x, y], dir: [dx, dy] };
      if (hit.ci === hit.len - 1)
        return hit.spiky
          ? { kind: "spikyTail", target: hit.sid, gap, hitCell: [x, y], dir: [dx, dy] }
          : { kind: "tail", target: hit.sid, gap, hitCell: [x, y], dir: [dx, dy] };
      if (hit.ci === 0) return { kind: "head", target: hit.sid, gap, hitCell: [x, y], dir: [dx, dy] };
      return { kind: "body", target: hit.sid, gap, hitCell: [x, y], dir: [dx, dy] };
    }
    // портал: направление сохраняется; занятость прочитана выше — лёгшая змея
    // его перекрывает. Встаём на клетку ПЕРЕД выходом: выход читается как обычная.
    const g = board.gates && board.gates.get(ckey(x, y));
    if (g) { gap.push([x, y]); x = g[0] - dx; y = g[1] - dy; continue; }
    // клетка пуста и открыта — поворот гнёт луч (спину проверили выше)
    if (t) [dx, dy] = SIDES[t[0] === from ? t[1] : t[0]];
    gap.push([x, y]);
  }
}

const clone = (snakes) => snakes.map((s) => ({ ...s, cells: s.cells.map((c) => [c[0], c[1]]) }));

function applyEat(snakes, eaterId, ray) {
  const prey = snakes.find((s) => s.id === ray.target);
  const food = new Set(prey.cells.map(([x, y]) => ckey(x, y)));
  const path = ray.gap.concat(prey.cells.slice().reverse());
  let cells = snakes.find((s) => s.id === eaterId).cells.map((c) => c.slice());
  for (const p of path) {
    cells.unshift([p[0], p[1]]);
    if (!food.has(ckey(p[0], p[1]))) cells.pop();
  }
  return snakes
    .filter((s) => s.id !== ray.target)
    .map((s) => (s.id === eaterId ? { ...s, cells } : s));
}

const maxLen = (snakes) => Math.max(0, ...snakes.map((s) => s.cells.length));

/* ---------- подсказка ----------
   Первый ход настоящей лучшей линии теми же raycast/applyEat — совет не может
   разойтись с правилами. План кэшируется: пока игрок идёт по нему, дальше даром. */
const stateKey = (snakes) =>
  snakes.map((s) => s.cells.map((c) => c.join(".")).join(";")).sort().join("|");

function legalMoves(snakes, W, H, board) {
  const out = [];
  for (const s of snakes) {
    if (s.sleep) continue;               // спящая не ходит, но её едят
    const ray = raycast(snakes, s.id, W, H, board);
    if (ray.kind === "tail") out.push({ sid: s.id, next: applyEat(snakes, s.id, ray) });
    else if (ray.kind === "edge") out.push({ sid: s.id, next: snakes.filter((q) => q.id !== s.id) });
  }
  return out;
}

// Кратчайший путь к ПОТОЛКУ, не к первой звезде; бюджет узлов общий, чтобы не
// подвесить вкладку. out.exhausted отличает «не нашёл за бюджет» от «нельзя»:
// на первое нельзя отвечать игроку «непроходимо».
function planGoal(level, snakes, board, out) {
  const budget = { left: 150000 };
  let seq = null;
  const dfs = (sn, d, cap, path, seen) => {
    if (maxLen(sn) >= (level.ceiling || level.target)) { seq = path.slice(); return true; }
    if (d >= cap || budget.left <= 0) return false;
    const k = stateKey(sn) + "#" + d;
    if (seen.has(k)) return false;
    seen.add(k); budget.left--;
    for (const m of legalMoves(sn, level.w, level.h, board)) {
      path.push({ k: stateKey(sn), sid: m.sid });
      if (dfs(m.next, d + 1, cap, path, seen)) return true;
      path.pop();
    }
    return false;
  };
  for (let cap = 1; cap <= snakes.length && budget.left > 0; cap++) {
    if (dfs(snakes, 0, cap, [], new Set())) return seq;
  }
  if (out && budget.left <= 0) out.exhausted = true;
  return null;
}

// прогон списка ходов механикой игры: приёмка уровня и карта «состояние → ход»
// для подсказки по задуманному плану
function walkSids(level, snakes, sids, board) {
  const steps = [];
  let sn = snakes;
  for (const sid of sids) {
    if (!sn.some((s) => s.id === sid)) return { bad: "змея " + sid + " уже съедена", steps };
    steps.push({ k: stateKey(sn), sid });
    const ray = raycast(sn, sid, level.w, level.h, board);
    if (ray.kind === "tail") sn = applyEat(sn, sid, ray);
    else if (ray.kind === "edge") sn = sn.filter((q) => q.id !== sid);
    else return { bad: "ход ведёт в аварию: " + ray.kind, steps };
  }
  return { steps, len: maxLen(sn), left: sn.length };
}

// проигрывание плана до конца — им принимаются рекордные уровни
function replayPlan(level, snakes, plan, board) {
  const map = new Map(plan.map((st) => [st.k, st.sid]));
  let sn = snakes, steps = 0;
  while (steps < 80) {
    const sid = map.get(stateKey(sn));
    if (sid == null) break;
    const ray = raycast(sn, sid, level.w, level.h, board);
    if (ray.kind === "tail") sn = applyEat(sn, sid, ray);
    else if (ray.kind === "edge") sn = sn.filter((q) => q.id !== sid);
    else return { len: 0, steps, broken: true };
    steps++;
  }
  return { len: maxLen(sn), steps, broken: false };
}

function planLongest(level, snakes, board) {
  const total = (sn) => sn.reduce((t, s) => t + s.cells.length, 0);
  let layer = [{ sn: snakes, k: stateKey(snakes), from: null, sid: null }];
  let best = maxLen(snakes), bestNode = null;
  for (let d = 0; d < 60 && layer.length; d++) {
    const next = [], seen = new Set();
    for (const nd of layer) {
      for (const m of legalMoves(nd.sn, level.w, level.h, board)) {
        const k = stateKey(m.next);
        if (seen.has(k)) continue;
        seen.add(k);
        const node = { sn: m.next, k, from: nd, sid: m.sid };
        if (maxLen(m.next) > best) { best = maxLen(m.next); bestNode = node; }
        next.push(node);
      }
    }
    next.sort((a, b) => (maxLen(b.sn) - maxLen(a.sn)) || (total(b.sn) - total(a.sn)));
    layer = next.slice(0, 160);
  }
  if (!bestNode) return null;
  const path = [];              // ссылка на родителя вместо копии пути в каждом узле
  for (let n = bestNode; n.from; n = n.from) path.unshift({ k: n.from.k, sid: n.sid });
  return path;
}

/* Может ли змея ещё вырасти — точный ответ (вылет не растит, но открывает лучи;
   змей строго меньше с каждым ходом — обход конечен). Бюджет исчерпан → «может»:
   закончить партию рано хуже, чем дать лишний ход. beam-ширина 160 в planLongest
   даёт то же, что 320, на всех замеренных полях. */
function canGrow(level, snakes, board, base) {
  const seen = new Set([stateKey(snakes)]);
  const stack = [snakes];
  let visited = 0;
  while (stack.length) {
    if (++visited > 20000) return true;
    const st = stack.pop();
    for (const m of legalMoves(st, level.w, level.h, board)) {
      if (maxLen(m.next) > base) return true;
      const k = stateKey(m.next);
      if (seen.has(k)) continue;
      seen.add(k);
      stack.push(m.next);
    }
  }
  return false;
}

function buildEatMove(snakes, sid, ray) {
  const eater = snakes.find((s) => s.id === sid);
  const prey = snakes.find((s) => s.id === ray.target);
  const pathCells = ray.gap.concat(prey.cells.slice().reverse());
  const foodFlags = pathCells.map((_, i) => i >= ray.gap.length);
  return {
    kind: "eat",
    moverId: sid,
    preyId: prey.id,
    n0: eater.cells.length,
    trackCells: eater.cells.slice().reverse().concat(pathCells),
    pathCells, foodFlags,
    preyCells: prey.cells.map((c) => c.slice()),
    gained: prey.cells.length,
    finalSnakes: applyEat(clone(snakes), sid, ray),
  };
}

function buildLaunchMove(snakes, sid, ray) {
  const s = snakes.find((q) => q.id === sid);
  const n0 = s.cells.length;
  const [dx, dy] = ray.dir;
  const pathCells = ray.gap.map((c) => c.slice());     // луч мог гнуться в поворотах
  let [x, y] = pathCells.length ? pathCells[pathCells.length - 1] : s.cells[0];
  for (let i = 0; i < n0 + 1; i++) { x += dx; y += dy; pathCells.push([x, y]); }
  return {
    kind: "launch",
    moverId: sid,
    preyId: null,
    n0,
    trackCells: s.cells.slice().reverse().concat(pathCells),
    pathCells,
    foodFlags: pathCells.map(() => false),
    preyCells: null,
    gained: 0,
    lost: n0,
    lostAt: s.cells[0].slice(),
    finalSnakes: clone(snakes).filter((q) => q.id !== sid),
  };
}

/* ================= «Ручной» — операции редактора =================
   Обратное построение руками: на доске стартовое состояние, первый разрез —
   последний ход решения. Правку судит прогон плана кодом игры (edRun), а не
   геометрия редактора: не прошёл — правка не случилась. ed: { w, h, rocks,
   bridges, turns, portals, snakes (+color/decoy), plan: [{sid, prey}],
   final/finalId — эталон рисунка, autoTiles — плитки, рождённые пяткой. */

const HAND_WHY = {
  self: "луч упирается в своё же тело",
  rock: "луч упирается в валун",
  edge: "луч уходит за край поля",
  head: "луч упирается в чужую голову",
  body: "луч упирается в чужое тело",
  spikyTail: "хвост жертвы колючий",
  turnBack: "луч бьётся в стенку поворота",
  loop: "луч замкнулся в кольце порталов",
};

const edEmpty = (w, h) => ({ w, h, rocks: [], bridges: [], turns: [], portals: [],
  snakes: [], plan: [], final: null, finalId: null, nextId: 1, autoTiles: [] });
const edCellsEq = (a, b) => a.length === b.length && a.every((c, i) => c[0] === b[i][0] && c[1] === b[i][1]);
const edInside = (ed, [x, y]) => x >= 0 && y >= 0 && x < ed.w && y < ed.h;
const edOccSet = (ed) => {
  const o = new Set();
  for (const s of ed.snakes) for (const [x, y] of s.cells) o.add(ckey(x, y));
  return o;
};
const edRockSet = (ed) => new Set(ed.rocks.map(([x, y]) => ckey(x, y)));
const edFloorAt = (ed, [x, y]) =>
  ed.rocks.some((c) => c[0] === x && c[1] === y) ||
  ed.bridges.some((c) => c[0] === x && c[1] === y) ||
  ed.turns.some((c) => c[0] === x && c[1] === y) ||
  ed.portals.some((p) => (p[0] === x && p[1] === y) || (p[2] === x && p[3] === y));

// прогон плана механикой игры — источник правды: луч обязан съесть задуманную
// жертву, а последний обед — собрать в точности нарисованную змею
function edRun(ed) {
  const bd = boardOf(ed);
  const states = [clone(ed.snakes)], rays = [];
  let sn = states[0];
  for (let i = 0; i < ed.plan.length; i++) {
    const mv = ed.plan[i];
    const flunk = (why) => ({ states, rays, bad: i, why });
    const s = sn.find((q) => q.id === mv.sid);
    if (!s) return flunk("едок уже съеден");
    if (s.sleep) return flunk("спящая не ходит");
    const ray = raycast(sn, mv.sid, ed.w, ed.h, bd);
    if (ray.kind !== "tail") return flunk(HAND_WHY[ray.kind] || "ход не выходит");
    if (ray.target !== mv.prey) return flunk("луч перехватила другая змея");
    rays.push({ from: s.cells[0].slice(), ray });
    sn = applyEat(sn, mv.sid, ray);
    states.push(sn);
  }
  if (ed.plan.length) {
    const fin = sn.find((q) => q.id === ed.finalId);
    if (!fin || !edCellsEq(fin.cells, ed.final))
      return { states, rays, bad: ed.plan.length - 1, why: "финал расходится с рисунком" };
  }
  return { states, rays };
}

// тень решения: клетки, по которым летят лучи плана, и клетки, где они
// останавливаются (хвосты жертв); сюда обманкам и полу хода нет
function edShadow(run) {
  const beam = new Set(), stop = new Set();
  for (const r of run.rays) {
    for (const [x, y] of r.ray.gap) beam.add(ckey(x, y));
    if (r.ray.hitCell) stop.add(ckey(r.ray.hitCell[0], r.ray.hitCell[1]));
  }
  return { beam, stop };
}

const edRoles = (ed) => {
  const eats = new Set(), eaten = new Set();
  for (const m of ed.plan) { eats.add(m.sid); eaten.add(m.prey); }
  return { eats, eaten };
};

const edNewColor = (ed, near) =>
  ORDER[(ORDER.indexOf(near) + 1 + (ed.nextId % (ORDER.length - 2))) % ORDER.length];

/* Разрез по ребру b: передние b клеток — жертва (стоит на месте), задняя часть —
   едок, наследующий id (поздние ходы плана находят его — к их моменту змея уже
   собрана этим обедом). Новый обед встаёт первым ходом; b=1 — яблоко. */
function edCut(ed, sid, b) {
  const M = ed.snakes.find((s) => s.id === sid);
  if (!M || M.decoy || M.apple) return null;
  const n = M.cells.length;
  if (b < 1 || n - b < 2) return null;               // едоку нужны голова и шея
  const B = { id: "e" + ed.nextId, color: edNewColor(ed, M.color),
    cells: M.cells.slice(0, b).map((c) => c.slice()),
    ...(b === 1 ? { apple: true, sleep: true } : {}) };
  const A = { ...M, cells: M.cells.slice(b).map((c) => c.slice()) };
  delete A.sleep;                                    // едок не спит: сон снимается разрезом
  return { ...ed, nextId: ed.nextId + 1,
    snakes: ed.snakes.map((s) => (s.id === sid ? A : s)).concat([B]),
    plan: [{ sid: A.id, prey: B.id }, ...ed.plan] };
}

/* Разрез на изгибе: клетка за жертвой уходит в зазор с плиткой поворота, хвост
   дорастает на клетку. Возвращает проверенный прогоном ed и плитку для призрака —
   ставит её игрок кнопкой. */
function edCutTurn(ed, sid, b) {
  const M = ed.snakes.find((s) => s.id === sid);
  if (!M || M.decoy || M.apple) return null;
  const n = M.cells.length;
  if (b < 1 || n - b < 2) return null;
  const g = M.cells[b];                              // будущая клетка зазора
  const aBody = M.cells.slice(b + 1).map((c) => c.slice());
  const hd = aBody[0], stop = M.cells[b - 1];        // голова едока и хвост жертвы
  const sIn = sideName([hd[0] - g[0], hd[1] - g[1]]);
  const sOut = sideName([stop[0] - g[0], stop[1] - g[1]]);
  // прямой пролёт плитки не требует — этим местом владеет обычный разрез
  if (SIDES[sIn][0] === -SIDES[sOut][0] && SIDES[sIn][1] === -SIDES[sOut][1]) return null;
  if (edFloorAt(ed, g)) return null;                 // пол на клетке зазора уже занят
  let cands;
  if (aBody.length === 1) {
    // взгляд задаёт шея-хвост: вариант ровно один — строго напротив зазора
    cands = [[2 * hd[0] - g[0], 2 * hd[1] - g[1]]];
  } else {
    if (2 * hd[0] - aBody[1][0] !== g[0] || 2 * hd[1] - aBody[1][1] !== g[1]) return null;
    const tl = aBody[aBody.length - 1];
    cands = [[tl[0] + 1, tl[1]], [tl[0] - 1, tl[1]], [tl[0], tl[1] + 1], [tl[0], tl[1] - 1]];
  }
  const tile = [g[0], g[1], sIn, sOut];
  const occ = edOccSet(ed), rocks = edRockSet(ed);
  for (const ext of cands) {
    const k = ckey(ext[0], ext[1]);
    if (!edInside(ed, ext) || occ.has(k) || rocks.has(k)) continue;
    if (ext[0] === g[0] && ext[1] === g[1]) continue; // зазор обязан остаться пустым
    const B = { id: "e" + ed.nextId, color: edNewColor(ed, M.color),
      cells: M.cells.slice(0, b).map((c) => c.slice()),
      ...(b === 1 ? { apple: true, sleep: true } : {}) };
    const A = { ...M, cells: aBody.concat([ext]) };
    delete A.sleep;
    const next = { ...ed, nextId: ed.nextId + 1,
      snakes: ed.snakes.map((s) => (s.id === sid ? A : s)).concat([B]),
      plan: [{ sid: A.id, prey: B.id }, ...ed.plan],
      turns: [...ed.turns, tile],
      autoTiles: [...ed.autoTiles, ckey(g[0], g[1])] };
    if (edRun(next).bad == null) return { ed: next, tile };
  }
  return null;
}

/* Пятка: голова сходит на tails.length клеток своего тела (они освобождаются
   под зазор), хвост дорастает клетками tails. Изгибы зазора собираются в
   предложение плиток — ставит их игрок кнопкой; на бывшей голове плитка не
   нужна никогда (луч приходит тем же направлением, каким уходил). На рельсе
   может остаться одна клетка — тогда взгляд задаёт первая клетка хвоста, как
   у генератора; ляжет ли она на линию луча, рассудит прогон. Без этого
   короткому среднему куску не сделать зазор — а только зазор двигает его
   хвост под чужой прицел и запирает порядок ходов. */
function edRetreat(ed, sid, tails) {
  const A = ed.snakes.find((s) => s.id === sid);
  const k = tails.length;
  if (!A || A.decoy || A.apple || k < 1 || A.cells.length - k < 1) return null;
  const occ = edOccSet(ed), rocks = edRockSet(ed);
  let prev = A.cells[A.cells.length - 1];
  for (const c of tails) {
    const ck2 = ckey(c[0], c[1]);
    if (!edInside(ed, c) || occ.has(ck2) || rocks.has(ck2)) return null;
    if (Math.abs(c[0] - prev[0]) + Math.abs(c[1] - prev[1]) !== 1) return null;
    occ.add(ck2);
    prev = c;
  }
  const tiles = [];
  let bendOk = true;
  for (let i = k - 1; i >= 1; i--) {
    const c = A.cells[i], p = A.cells[i + 1], nx = A.cells[i - 1];
    const din = [p[0] - c[0], p[1] - c[1]], dout = [nx[0] - c[0], nx[1] - c[1]];
    if (din[0] === -dout[0] && din[1] === -dout[1]) continue;
    if (edFloorAt(ed, c)) { bendOk = false; break; } // изгиб на занятом полу не согнуть
    tiles.push([c[0], c[1], sideName(din), sideName(dout)]);
  }
  const next = { ...ed, snakes: ed.snakes.map((s) =>
    (s.id === sid ? { ...s, cells: A.cells.slice(k).concat(tails.map((c) => c.slice())) } : s)) };
  return { ed: next, tiles: bendOk ? tiles : null, freed: A.cells.slice(0, k) };
}

// обратный шаг пятки: голова наползает на первую клетку луча, хвост втягивается;
// пяточная плитка снимается, ручные остаются
function edAdvance(ed, sid) {
  const A = ed.snakes.find((s) => s.id === sid);
  if (!A || A.decoy || A.apple || A.cells.length < 2) return null;
  const f = facing(A.cells);
  const p = [A.cells[0][0] + f[0], A.cells[0][1] + f[1]];
  if (!edInside(ed, p)) return null;
  const pk = ckey(p[0], p[1]);
  if (edOccSet(ed).has(pk) || edRockSet(ed).has(pk)) return null;
  let turns = ed.turns, autoTiles = ed.autoTiles;
  if (autoTiles.includes(pk)) {
    turns = turns.filter(([x, y]) => ckey(x, y) !== pk);
    autoTiles = autoTiles.filter((q) => q !== pk);
  }
  return { ...ed, turns, autoTiles, snakes: ed.snakes.map((s) =>
    (s.id === sid ? { ...s, cells: [p, ...A.cells.slice(0, -1).map((c) => c.slice())] } : s)) };
}

function edSetStatus(ed, sid, st) {
  return { ...ed, snakes: ed.snakes.map((s) => {
    if (s.id !== sid || s.apple) return s;
    const q = { ...s };
    delete q.spiky; delete q.sleep;
    if (st === "spiky") q.spiky = true;
    if (st === "sleep") q.sleep = true;
    return q;
  }) };
}

function edAddDecoy(ed, cells) {
  const s = { id: "e" + ed.nextId, decoy: true,
    color: ORDER[(ed.nextId * 5 + 2) % ORDER.length],
    cells: cells.map((c) => c.slice()),
    ...(cells.length === 1 ? { apple: true, sleep: true } : {}) };
  return { ...ed, nextId: ed.nextId + 1, snakes: [...ed.snakes, s] };
}

const edDropDecoy = (ed, sid) => {
  const s = ed.snakes.find((q) => q.id === sid);
  if (!s || !s.decoy) return null;
  return { ...ed, snakes: ed.snakes.filter((q) => q.id !== sid) };
};

// пол кладётся/снимается тапом, плитка тапами крутится по углам; валун под тело
// не встаёт, мост и плитка — могут (змея их честно перекрывает)
const HAND_TURNS = [["n", "e"], ["e", "s"], ["s", "w"], ["w", "n"]];
function edToggleFloor(ed, tool, x, y) {
  const same = (c) => c[0] === x && c[1] === y;
  if (tool === "rock") {
    if (ed.rocks.some(same)) return { ...ed, rocks: ed.rocks.filter((c) => !same(c)) };
    if (edFloorAt(ed, [x, y]) || edOccSet(ed).has(ckey(x, y))) return null;
    return { ...ed, rocks: [...ed.rocks, [x, y]] };
  }
  if (tool === "bridge") {
    if (ed.bridges.some(same)) return { ...ed, bridges: ed.bridges.filter((c) => !same(c)) };
    if (edFloorAt(ed, [x, y])) return null;
    return { ...ed, bridges: [...ed.bridges, [x, y]] };
  }
  if (tool === "turn") {
    const cur = ed.turns.findIndex(same);
    if (cur >= 0) {
      const [, , a, b] = ed.turns[cur];
      const at = HAND_TURNS.findIndex(([p, q]) => p === a && q === b);
      const rest = ed.turns.filter((_, i) => i !== cur);
      const auto = ed.autoTiles.filter((q) => q !== ckey(x, y)); // тронул руками — плитка теперь ручная
      if (at >= 0 && at < HAND_TURNS.length - 1)
        return { ...ed, autoTiles: auto, turns: [...rest, [x, y, ...HAND_TURNS[at + 1]]] };
      return { ...ed, autoTiles: auto, turns: rest };
    }
    if (edFloorAt(ed, [x, y])) return null;
    return { ...ed, turns: [...ed.turns, [x, y, "n", "e"]] };
  }
  return null;
}

// портал ставится двумя тапами: вход, потом выход; тап по готовому — снятие пары
function edPortalTap(ed, from, x, y) {
  const hit = ed.portals.findIndex((p) => (p[0] === x && p[1] === y) || (p[2] === x && p[3] === y));
  if (hit >= 0) return { ed: { ...ed, portals: ed.portals.filter((_, i) => i !== hit) } };
  if (edFloorAt(ed, [x, y])) return null;
  if (!from) return { from: [x, y] };
  if (from[0] === x && from[1] === y) return null;
  return { ed: { ...ed, portals: [...ed.portals, [from[0], from[1], x, y]] } };
}

// живая обманка: есть обед или хвост под чьим-то лучом (колючий — тоже);
// мёртвая — мебель, в песочнице это пометка, не запрет
function edLively(ed) {
  const sn = clone(ed.snakes), bd = boardOf(ed);
  const rc = new Map();
  for (const s of sn) if (!s.sleep) rc.set(s.id, raycast(sn, s.id, ed.w, ed.h, bd));
  const out = new Set();
  for (const s of sn) {
    if (!s.decoy) continue;
    const own = rc.get(s.id);
    if (own && own.kind === "tail") { out.add(s.id); continue; }
    for (const [sid, r] of rc)
      if (sid !== s.id && (r.kind === "tail" || r.kind === "spikyTail") && r.target === s.id) {
        out.add(s.id);
        break;
      }
  }
  return out;
}

/* Ручной уровень в crafted-формат (план, отметки, урок — подсказка и обмен
   работают как есть). Потолок: длина рисунка (walkSids подтверждает) плюс
   beam-поиск сверху — обманки съедобны, доска может дотягиваться выше. */
function handToCrafted(ed, ordinal) {
  const snakes = ed.snakes.map((s) => ({
    cells: s.cells.map((c) => c.slice()),
    ...(s.spiky ? { spiky: true } : {}),
    ...(s.apple ? { apple: true, sleep: true } : s.sleep ? { sleep: true } : {}),
  }));
  const idOf = new Map(ed.snakes.map((s, i) => [s.id, "s" + i]));
  const plan = ed.plan.map((m) => idOf.get(m.sid));
  const lvl = { w: ed.w, h: ed.h }, bd = boardOf(ed);
  const got = walkSids(lvl, withIds(snakes), plan, bd);
  if (got.bad || got.len < ed.final.length) return null;
  let ceiling = ed.final.length;
  const beam = planLongest(lvl, withIds(snakes), bd);
  if (beam) {
    const rp = replayPlan(lvl, withIds(snakes), beam, bd);
    if (!rp.broken && rp.len > ceiling) ceiling = rp.len;
  }
  const marks = marksOf(ceiling, Math.max(...snakes.map((s) => s.cells.length)));
  const мех = [];
  if (snakes.some((s) => s.apple)) мех.push("яблоки");
  if (snakes.some((s) => s.spiky)) мех.push("колючие");
  if (snakes.some((s) => s.sleep && !s.apple)) мех.push("спящие");
  if (ed.rocks.length) мех.push("валуны");
  if (ed.bridges.length) мех.push("мосты");
  if (ed.turns.length) мех.push("повороты");
  if (ed.portals.length) мех.push("порталы");
  return { w: ed.w, h: ed.h, snakes,
    rocks: ed.rocks.map((c) => c.slice()),
    bridges: ed.bridges.map((c) => c.slice()),
    turns: ed.turns.map((t) => t.slice()),
    portals: ed.portals.map((p) => p.slice()),
    preset: "ручной", seed: 0, cfg: null,
    name: "Ручной " + ordinal, mode: "goal",
    ceiling, marks, target: marks[0], plan,
    lesson: "Свой уровень, нарисован руками · задумано " + ходов(ed.plan.length)
      + (мех.length ? " · " + мех.join(", ") : "") };
}

/* ---------- геометрия для плавного скольжения ---------- */
const toPx = ([x, y]) => [x * CS + CS / 2, y * CS + CS / 2];

// геометрия скольжения стоит на «соседние клетки ровно на CS»; портальный разрыв
// это ломает — такой отрезок не интерполируется, а перескакивается
const jumped = (a, b) => Math.abs(a[0] - b[0]) + Math.abs(a[1] - b[1]) > CS * 1.5;

function ptAt(P, s) {
  const maxI = P.length - 1;
  let i = Math.floor(s / CS);
  if (i < 0) i = 0;
  if (i >= maxI) return [P[maxI][0], P[maxI][1]];
  const f = (s - i * CS) / CS;
  if (jumped(P[i], P[i + 1])) return f < 0.5 ? [P[i][0], P[i][1]] : [P[i + 1][0], P[i + 1][1]];
  return [P[i][0] + (P[i + 1][0] - P[i][0]) * f, P[i][1] + (P[i + 1][1] - P[i][1]) * f];
}

function samplePts(P, s0, s1) {
  const res = [ptAt(P, s0)];
  for (let k = Math.floor(s0 / CS) + 1; k * CS < s1; k++)
    if (k >= 0 && k < P.length) res.push(P[k]);
  const e = ptAt(P, s1);
  const last = res[res.length - 1];
  if (Math.abs(e[0] - last[0]) + Math.abs(e[1] - last[1]) > 0.4) res.push(e);
  return res;
}

// разрыв на портале рисуем как новый подпуть, иначе тело протянется через всю доску
const dStr = (pts) => pts.map((p, i) =>
  (i && !jumped(pts[i - 1], p) ? "L" : "M") + p[0].toFixed(1) + " " + p[1].toFixed(1)).join(" ");

function segAngle(P, i) {
  // за порталом направление сохраняется, поэтому угол берём у ближайшего обычного отрезка
  let j = i;
  while (j < P.length - 1 && jumped(P[j], P[j + 1])) j++;
  while (j > 0 && jumped(P[j], P[j + 1])) j--;
  if (j >= P.length - 1 || jumped(P[j], P[j + 1])) return 0;
  return (Math.atan2(P[j + 1][1] - P[j][1], P[j + 1][0] - P[j][0]) * 180) / Math.PI;
}
function lerpAngle(a, b, t) {
  let d = ((b - a + 540) % 360) - 180;
  return a + d * t;
}
function angleAt(P, s) {
  const maxI = P.length - 1;
  let i = Math.floor(s / CS);
  if (i >= maxI) i = maxI - 1;
  if (i < 0) i = 0;
  const f = (s - i * CS) / CS;
  const a = segAngle(P, i);
  if (f < 0.35 && i > 0) return lerpAngle(segAngle(P, i - 1), a, f / 0.35);
  return a;
}

